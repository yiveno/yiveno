CREATE OR REPLACE FUNCTION "public"."get_user_subscription_status"("user_uuid" "uuid") RETURNS TABLE("tier" "text", "status" "text", "current_period_end" timestamp with time zone, "cancel_at_period_end" boolean)
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO 'public', 'pg_temp'
    AS $$
BEGIN
  RETURN QUERY
  SELECT 
    s.tier,
    s.status,
    s.current_period_end,
    s.cancel_at_period_end
  FROM public.subscriptions s
  WHERE s.user_id = user_uuid
    AND s.status = 'active'
    AND s.current_period_end > NOW()
  ORDER BY s.current_period_end DESC
  LIMIT 1;
END;
$$;


